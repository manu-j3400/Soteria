"""
Build a hand-labeling sheet for flagged releases that no ground-truth
source already marks as malicious.

Writes to <data>/scores/<tag>/:
  labels.csv        one row per sampled release; fill in `label`
                    (malicious / benign / unsure) and fix `pattern`.
                    Rerunning keeps label/pattern/notes already filled in.
  review/<n>.md     the release's top-scoring units and dataflow findings,
                    for reading

Rules come from precision.RULES; the df_* rules are sampled only when
<data>/scores/dataflow/packages.csv exists.

`pattern` is pre-filled with a heuristic guess (see suggest_pattern) so the
labeler only corrects it. Patterns line up with Feross's list where they can:
binary_fetcher, obfuscated_licensing, bundled_vendored, plus the extra
buckets that showed up in practice.

review/*.md holds plaintext code. If antivirus removes one, that release
almost certainly contains known malware: label it malicious and note "AV".

Usage:
  python3 -I label_sheet.py --data ~/soteria_pypi_eval --tag baseline --n 150
"""
from __future__ import annotations

import argparse
import json
import random
import re
import sys
from collections import defaultdict
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from features import unpack_code  # noqa: E402
from precision import RULES, add_derived  # noqa: E402

PATTERNS = [
    "binary_fetcher", "obfuscated_licensing", "bundled_vendored", "generated_code",
    "test_code", "import_only_module", "subprocess_cli", "network_sdk",
    "security_tooling", "other",
]

_VENDOR = re.compile(r"(^|/)(_vendor|vendor|vendored|third_party|_bundled|externals?|site-packages)/")
_GENERATED = re.compile(r"(_pb2(_grpc)?\.py$|(^|/)_?generated/|openapi|swagger)", re.I)
_GENERATED_TXT = re.compile(r"(DO NOT EDIT|auto-?generated|Generated by|generated code)", re.I)
_TEST = re.compile(r"(^|/)(tests?|testing)/|(^|/)test_[^/]*\.py$|_test\.py$|conftest\.py$")
_SECURITY_WORDS = re.compile(r"(pentest|exploit|payload|red.?team|ctf|fuzz|scanner|nmap|sqlmap|"
                             r"malware|forensic|osint|honeypot|c2\b|reverse.?shell)", re.I)


def suggest_pattern(units: list[dict], summary: str = "") -> str:
    """Guess why the top flagged unit tripped the model."""
    if not units:
        return "other"
    top = max(units, key=lambda u: u["prob"])
    cc, path, raw = top.get("cc", {}), top["file"], top.get("raw", "")
    if cc.get("cc_obfuscator_marker") or cc.get("cc_obf_name_ratio", 0) > 0.3:
        return "obfuscated_licensing"
    if cc.get("cc_network_call") and (cc.get("cc_platform_check") or cc.get("cc_chmod_exec")
                                      or cc.get("cc_url_binary_ext") or cc.get("cc_path_pkg_relative")):
        return "binary_fetcher"
    if _VENDOR.search(path):
        return "bundled_vendored"
    if _GENERATED.search(path) or _GENERATED_TXT.search(raw[:2000]):
        return "generated_code"
    if _TEST.search(path):
        return "test_code"
    if _SECURITY_WORDS.search(summary or ""):
        return "security_tooling"
    body = [l for l in raw.splitlines() if l.strip() and not l.lstrip().startswith("#")]
    if top["unit"] == "<module>" and body and \
            sum(l.startswith(("import ", "from ")) for l in body) / len(body) > 0.6:
        return "import_only_module"
    if re.search(r"\bsubprocess\.|os\.system|os\.popen", raw):
        return "subprocess_cli"
    if cc.get("cc_network_call"):
        return "network_sdk"
    return "other"


def load_units(sdir: Path) -> dict[tuple[str, str], list[dict]]:
    by_pkg: dict[tuple[str, str], list[dict]] = defaultdict(list)
    with open(sdir / "units.jsonl") as fh:
        for line in fh:
            u = json.loads(line)
            u["raw"] = unpack_code(u["raw"])
            by_pkg[(u["name"], str(u["version"]))].append(u)
    return by_pkg


def load_findings(root: Path, keys: set) -> dict[tuple[str, str], list[dict]]:
    path = root / "scores" / "dataflow" / "findings.jsonl"
    by_pkg: dict[tuple[str, str], list[dict]] = defaultdict(list)
    if path.exists():
        with open(path) as fh:
            for line in fh:
                f = json.loads(line)
                k = (f["name"], str(f["version"]))
                if k in keys:
                    f["raw"] = unpack_code(f["raw"])
                    by_pkg[k].append(f)
    return by_pkg


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--data", default="~/soteria_pypi_eval")
    p.add_argument("--tag", default="baseline")
    p.add_argument("--n", type=int, default=150, help="releases to sample per flag rule")
    p.add_argument("--seed", type=int, default=42)
    a = p.parse_args()

    root = Path(a.data).expanduser()
    sdir = root / "scores" / a.tag
    df = pd.read_csv(sdir / "packages_crosschecked.csv", dtype={"version": str})
    df["known_malicious"] = df["known_malicious"].fillna("")
    by_pkg = load_units(sdir)
    rng = random.Random(a.seed)

    # sample separately per flag rule so each rule gets its own precision estimate
    picked: dict[tuple[str, str], set[str]] = defaultdict(set)
    df = add_derived(df, root)
    for rule, col in RULES.items():
        if col not in df:
            continue
        pool = df[(df[col] > 0) & (df["known_malicious"] == "")]
        keys = list(zip(pool["name"], pool["version"]))
        for k in rng.sample(keys, min(a.n, len(keys))):
            picked[k].add(rule)

    findings = load_findings(root, set(picked))
    df_cols = df.attrs.get("df_rules", [])
    review = sdir / "review"
    review.mkdir(exist_ok=True)
    rows = []
    idx = df.set_index(["name", "version"])
    for i, (key, rules) in enumerate(sorted(picked.items())):
        r = idx.loc[key]
        if isinstance(r, pd.DataFrame):
            r = r.iloc[0]
        units = sorted(by_pkg.get(key, []), key=lambda u: -u["prob"])
        summary = str(r.get("summary") or "")
        rows.append({"id": i, "name": key[0], "version": key[1], "sampled_for": ",".join(sorted(rules)),
                     "new_project": r.get("new_project"), "max_prob": r.get("max_prob"),
                     "max_unit": r.get("max_unit"), "risk_cats": r.get("risk_cats"),
                     "pypi_status": r.get("pypi_status"),
                     "df_rules": ",".join(c for c in df_cols if r.get(c, 0) > 0), "summary": summary[:120],
                     "pattern": suggest_pattern(units, summary), "label": "", "notes": ""})
        md = [f"# {key[0]} {key[1]}", "", f"summary: {summary}", f"pypi: https://pypi.org/project/{key[0]}/{key[1]}/",
              f"status now: {r.get('pypi_status')}  |  risk: {r.get('risk_cats')}", ""]
        risky = [u for u in units if u.get("risk")]
        for u in (units[:3] + [u for u in risky if u not in units[:3]][:2]):
            md += [f"## {u['file']}:{u['line']} {u['unit']}  p={u['prob']}  risk={u.get('risk')}",
                   f"cc: {u.get('cc')}", "```python", u["raw"][:4000], "```", ""]
        for f in findings.get(key, [])[:5]:
            md += [f"## dataflow {f['rule']}: {f['file']}:{f['line']} {f['func']}  install={f['install_time']}",
                   "```python", f["raw"][:4000], "```", ""]
        (review / f"{i:04d}.md").write_text("\n".join(md))

    out = pd.DataFrame(rows)
    prev_path = sdir / "labels.csv"
    if prev_path.exists() and len(out):
        prev = pd.read_csv(prev_path, dtype={"version": str}).fillna("")
        prev = {(r.name, r.version): r for r in prev[prev["label"] != ""].itertuples()}
        for i, k in enumerate(zip(out["name"], out["version"])):
            if k in prev:
                for c in ("label", "pattern", "notes"):
                    out.loc[i, c] = getattr(prev[k], c)
        print(f"kept {out['label'].ne('').sum()} existing labels from {prev_path}")
    out.to_csv(sdir / "labels.csv", index=False)
    print(f"{len(out)} releases to label -> {sdir / 'labels.csv'}")
    print(out["pattern"].value_counts().to_string())


if __name__ == "__main__":
    main()
